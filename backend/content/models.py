from django.conf import settings
from django.contrib.postgres.fields import ArrayField
from django.db import models

from x_accounts.models import ContentDNA, XAccount

# X limits for posts written in OM2 (standard accounts).
POST_MAX_LENGTH = 280
THREAD_MIN_POSTS = 2
THREAD_MAX_POSTS = 10
POLL_MIN_OPTIONS = 2
POLL_MAX_OPTIONS = 4
POLL_OPTION_MAX_LENGTH = 25


class GenerationRun(models.Model):
    """One request to an AI provider for one X account, with everything needed to audit it."""

    class Status(models.TextChoices):
        SUCCEEDED = 'SUCCEEDED', 'Succeeded'
        FAILED = 'FAILED', 'Failed'

    x_account = models.ForeignKey(XAccount, on_delete=models.PROTECT, related_name='generation_runs')
    requested_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name='generation_runs'
    )
    provider = models.CharField(max_length=50)
    model_name = models.CharField(max_length=100)
    is_mock = models.BooleanField(default=False)
    requested_count = models.PositiveSmallIntegerField()
    requested_format = models.CharField(max_length=10, choices=ContentDNA.Format.choices, blank=True)
    instructions = models.CharField(max_length=1000, blank=True)
    # The Content DNA exactly as it was used, so later DNA edits never rewrite history.
    dna_snapshot = models.JSONField()
    prompt = models.TextField(blank=True)
    status = models.CharField(max_length=10, choices=Status.choices)
    error = models.CharField(max_length=500, blank=True)
    input_tokens = models.PositiveIntegerField(default=0)
    output_tokens = models.PositiveIntegerField(default=0)
    estimated_cost_usd = models.DecimalField(max_digits=10, decimal_places=6, default=0)
    duration_ms = models.PositiveIntegerField(default=0)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at', '-id']

    def __str__(self):
        return f'{self.provider} run for @{self.x_account.handle} ({self.status})'


class ContentItem(models.Model):
    """A post for one X account: generated by AI or written manually, then reviewed."""

    class Status(models.TextChoices):
        DRAFT = 'DRAFT', 'Draft'
        APPROVED = 'APPROVED', 'Approved'
        REJECTED = 'REJECTED', 'Rejected'

    class Source(models.TextChoices):
        AI = 'AI', 'AI generated'
        MANUAL = 'MANUAL', 'Manual'

    x_account = models.ForeignKey(XAccount, on_delete=models.PROTECT, related_name='content_items')
    generation_run = models.ForeignKey(
        GenerationRun, null=True, blank=True, on_delete=models.SET_NULL, related_name='items'
    )
    source = models.CharField(max_length=10, choices=Source.choices)
    status = models.CharField(max_length=10, choices=Status.choices, default=Status.DRAFT)
    format = models.CharField(max_length=10, choices=ContentDNA.Format.choices)
    # TEXT: the post. THREAD: unused (posts live in thread_posts). POLL: the question.
    body = models.CharField(max_length=POST_MAX_LENGTH * 2, blank=True)
    thread_posts = ArrayField(models.CharField(max_length=POST_MAX_LENGTH * 2), blank=True, default=list)
    poll_options = ArrayField(models.CharField(max_length=POLL_OPTION_MAX_LENGTH * 2), blank=True, default=list)
    theme = models.CharField(max_length=60, blank=True)
    language = models.CharField(max_length=10, choices=ContentDNA.Language.choices, blank=True)
    dna_snapshot = models.JSONField(null=True, blank=True)
    # Normalised text, used for exact-duplicate checks.
    fingerprint = models.CharField(max_length=64, db_index=True)
    duplicate_flags = models.JSONField(default=list, blank=True)
    validation_flags = models.JSONField(default=list, blank=True)
    rejection_reason = models.CharField(max_length=500, blank=True)
    # True once a person has changed the text (clears the mock-content warning).
    human_edited = models.BooleanField(default=False)
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name='+'
    )
    updated_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name='+'
    )
    reviewed_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name='+'
    )
    reviewed_at = models.DateTimeField(null=True, blank=True)
    version = models.PositiveIntegerField(default=1)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at', '-id']
        indexes = [models.Index(fields=['x_account', 'status', '-created_at'])]

    def __str__(self):
        return f'{self.get_format_display()} for @{self.x_account.handle} ({self.status})'

    @property
    def full_text(self):
        """All the text of the post, as one string."""
        parts = self.thread_posts if self.format == ContentDNA.Format.THREAD else [self.body, *self.poll_options]
        return '\n'.join(p for p in parts if p)


class ContentRevision(models.Model):
    """Append-only audit history: one row per change to a content item."""

    class Action(models.TextChoices):
        CREATED = 'CREATED', 'Created'
        EDITED = 'EDITED', 'Edited'
        APPROVED = 'APPROVED', 'Approved'
        REJECTED = 'REJECTED', 'Rejected'
        RESTORED = 'RESTORED', 'Restored to draft'

    item = models.ForeignKey(ContentItem, on_delete=models.CASCADE, related_name='revisions')
    version = models.PositiveIntegerField()
    action = models.CharField(max_length=10, choices=Action.choices)
    status = models.CharField(max_length=10, choices=ContentItem.Status.choices)
    format = models.CharField(max_length=10, choices=ContentDNA.Format.choices)
    body = models.CharField(max_length=POST_MAX_LENGTH * 2, blank=True)
    thread_posts = ArrayField(models.CharField(max_length=POST_MAX_LENGTH * 2), blank=True, default=list)
    poll_options = ArrayField(models.CharField(max_length=POLL_OPTION_MAX_LENGTH * 2), blank=True, default=list)
    note = models.CharField(max_length=500, blank=True)
    changed_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name='+')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at', '-id']

    def __str__(self):
        return f'{self.action} v{self.version} of item {self.item_id}'


class ShortLink(models.Model):
    """Cache of TinyURL short links, so each long URL is shortened only once."""

    long_url_hash = models.CharField(max_length=64, unique=True)
    long_url = models.TextField()
    short_url = models.URLField(max_length=200)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return self.short_url
